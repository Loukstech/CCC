export type CKey = keyof typeof RAW;
export type ConsoleStrings = Record<CKey, { fr: string; en: string }>;

export const C: ConsoleStrings = Object.fromEntries(
  Object.entries(RAW).map(([k, [fr, en]]) => [k, { fr, en }]),
) as ConsoleStrings;

/** Traduction d'une chaîne de la console, avec interpolation `{var}`. */
export function ct(lang: Lang, key: CKey, vars?: Record<string, string | number>): string {
  let s = C[key][lang];
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, String(v));
  return s;
}

